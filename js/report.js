const modal = document.querySelector('#resource-modal');
const modalContent = document.querySelector('#modal-content');
const modalScroll = document.querySelector('.modal-scroll');
const modalNavButtons = document.querySelectorAll('.modal-nav [data-section]');
const resourceCards = document.querySelectorAll('[data-resource]');
let previousFocus = null;

function programMarkup(program) {
  return `<article class="program-card"><span>${program[0]}</span><h4>${program[1]}</h4><p>${program[2]}</p><small>${program[3]}</small></article>`;
}

function reviewMarkup(review) {
  return `<article class="review-card"><header><strong>${review[0]}</strong><span aria-label="별점 5점">★★★★★</span></header><p>${review[1]}</p><small>${review[2]}</small></article>`;
}

function renderModal(item) {
  modalContent.innerHTML = `
    <section class="modal-content-section" id="modal-overview">
      <p class="modal-kicker">SELECTED TOURISM RESOURCE</p>
      <div class="modal-title-row"><h2 id="modal-title">${item.title}</h2><span class="modal-place-type">${item.type}</span></div>
      <p class="modal-lead">${item.lead}</p>
      <div class="modal-meta"><div><span>LOCATION</span><strong>${item.location}</strong></div><div><span>BEST TIME</span><strong>${item.time}</strong></div></div>
      <div class="modal-visuals">${item.visualLabels.map(label => `<div class="modal-visual"><span>${label}</span></div>`).join('')}</div>
      <div class="modal-tags" aria-label="관련 태그">${item.tags.map(tag => `<span>${tag}</span>`).join('')}</div>
    </section>
    <section class="modal-content-section" id="modal-experience">
      <div class="modal-section-heading"><span>EXPERIENCE PROGRAM</span><h3>이렇게 경험해 보세요</h3></div>
      <div class="program-grid">${item.programs.map(programMarkup).join('')}</div>
      <div class="visit-tip"><strong>VISIT TIP</strong><p>${item.tip}</p></div>
    </section>
    <section class="modal-content-section" id="modal-reviews">
      <div class="modal-section-heading"><span>VISITOR REVIEWS</span><h3>방문자가 남긴 이야기</h3></div>
      <div class="review-list">${item.reviews.map(reviewMarkup).join('')}</div>
    </section>`;
}

function setActiveNav(sectionName) {
  modalNavButtons.forEach(button => button.classList.toggle('active', button.dataset.section === sectionName));
}

function openModal(resourceId) {
  const item = resourceData[resourceId];
  if (!item) return;
  previousFocus = document.activeElement;
  renderModal(item);
  modal.hidden = false;
  document.body.classList.add('modal-open');
  modalScroll.scrollTop = 0;
  setActiveNav('overview');
  document.querySelector('.modal-close').focus();
}

function closeModal() {
  modal.hidden = true;
  document.body.classList.remove('modal-open');
  if (previousFocus) previousFocus.focus();
}

resourceCards.forEach(card => {
  card.addEventListener('click', () => openModal(card.dataset.resource));
  card.addEventListener('keydown', event => {
    if (event.key === 'Enter' || event.key === ' ') {
      event.preventDefault();
      openModal(card.dataset.resource);
    }
  });
});

document.querySelectorAll('[data-modal-close]').forEach(button => button.addEventListener('click', closeModal));

modalNavButtons.forEach(button => button.addEventListener('click', () => {
  const section = document.querySelector(`#modal-${button.dataset.section}`);
  if (!section) return;
  setActiveNav(button.dataset.section);
  modalScroll.scrollTo({ top: section.offsetTop, behavior: 'smooth' });
}));

modalScroll.addEventListener('scroll', () => {
  const sections = ['overview', 'experience', 'reviews'];
  let current = 'overview';
  sections.forEach(name => {
    const section = document.querySelector(`#modal-${name}`);
    if (section && modalScroll.scrollTop >= section.offsetTop - 140) current = name;
  });
  setActiveNav(current);
});

document.addEventListener('keydown', event => {
  if (modal.hidden) return;
  if (event.key === 'Escape') closeModal();
  if (event.key === 'Tab') {
    const focusable = [...modal.querySelectorAll('button,[tabindex="0"]')].filter(element => !element.hidden);
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
    if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
  }
});
